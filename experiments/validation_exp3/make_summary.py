"""
Writes RESULTS.md from results/*.json (no number is typed by hand).

    python experiments/validation_exp3/make_summary.py
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def load(n):
    return json.loads((HERE / "results" / f"exp3_{n}.json").read_text())


def ci(x, d=3):
    return f"[{x[0]:.{d}f}, {x[1]:.{d}f}]"


def main():
    sim, cal, abl = load("similarity"), load("calibration"), load("ablation")
    meta = abl["meta"]
    pop = meta["populations"]
    L = []
    w = L.append
    w("# Experiment 3 — results (synthetic data only)\n")
    w("Generated by `make_summary.py` from `results/*.json`. Protocol: `PROTOCOL.md` (SHA-256 of the file as analysed, i.e. with amendment A1: `%s`; the pre-amendment file committed first in `b58fa52` had SHA-256 `bd4d709ed7e23792d244fe26f9c869428ea63ea417fcafdd36ae44d77cbf267e`; both were committed before any data was generated). Every statement below is about data from the project's own generator; none is evidence about real banking fraud.\n" % meta["protocol_sha256"])
    w("## Data\n")
    w("| Role | Seed | Rows | Fraud rows | Fraud episodes | Dataset SHA-256 (transactions_with_features.csv) |")
    w("|---|---|---|---|---|---|")
    for role, seeds in (("validation", meta["seeds"]["validation"]), ("test", meta["seeds"]["test"])):
        for s in seeds:
            m = json.loads((HERE / "data_manifests" / f"seed_{s}_manifest.json").read_text())["summary"]
            w(f"| {role} | {s} | {m['transactions']:,} | {m['fraud_transactions']:,} | {m['episodes']} | `{meta['dataset_sha256'][str(s)]}` |")
    w(f"\nPooled validation: {pop['dev']['rows']:,} rows, {pop['dev']['fraud']:,} fraud. Pooled test: {pop['test']['rows']:,} rows, {pop['test']['fraud']:,} fraud "
      f"({pop['test']['p10_rows']:,} rows with at least 10 earlier transactions, all {pop['test']['p10_fraud']:,} fraud rows among them; {pop['test']['fraud_under_10_prior']} fraud rows have fewer than 10).\n")

    d = sim["discrimination_pooled_test"]
    w("## EXP3-SIM — Behavioral Similarity (deviation = 100 − similarity), pooled test, rows with ≥ 10 earlier transactions\n")
    dist = sim["distributions_deviation"]["all_p10"]
    w(f"Median deviation: legitimate {dist['legit']['median']}, fraud {dist['fraud']['median']} (IQR {dist['legit']['q25']}–{dist['legit']['q75']} versus {dist['fraud']['q25']}–{dist['fraud']['q75']}).\n")
    w("| Score | ROC-AUC (95 % CI) | PR-AUC (95 % CI) | Cliff's δ |")
    w("|---|---|---|---|")
    for k, label in (("s0_p10", "similarity deviation, served formula (S0)"), ("s1_p10", "variant: std floored at 0.5 (S1, exploratory)"),
                     ("classifier_p10", "default classifier score (for scale)"), ("combo_p10", "classifier + similarity (logistic, fitted on validation)")):
        v = d[k]
        w(f"| {label} | {v['roc_auc']:.3f} {ci(v['roc_auc_ci95'])} | {v['pr_auc']:.3f} {ci(v['pr_auc_ci95'])} | {v['cliffs_delta']:.3f} |")
    w(f"\nFraud prevalence in these rows: {sim['prevalence_p10_test']:.4f}. Per-seed ROC-AUC of S0: " + ", ".join(f"{s}: {v:.3f}" for s, v in sim["per_seed_roc_auc_s0_p10"].items()) + ".\n")
    inc = sim["incremental_value_over_classifier"]
    w(f"* Discriminatory value (interval of AUC excludes 0.5): **{'yes' if inc['interpretation_rule_met_discriminatory_value'] else 'no'}**.")
    w(f"* Added value over the classifier: PR-AUC difference {inc['combo_minus_classifier_pr_auc']['difference']:+.4f} {ci(inc['combo_minus_classifier_pr_auc']['ci95'], 4)} "
      f"(excludes 0: {inc['combo_minus_classifier_pr_auc']['excludes_zero']}); ROC-AUC difference {inc['combo_minus_classifier_roc_auc']['difference']:+.4f} {ci(inc['combo_minus_classifier_roc_auc']['ci95'], 4)} "
      f"(excludes 0: {inc['combo_minus_classifier_roc_auc']['excludes_zero']}). By the pre-specified rule the score **{'adds' if inc['combo_minus_classifier_pr_auc']['excludes_zero'] and inc['combo_minus_classifier_pr_auc']['difference'] > 0 else 'is not shown to add'}** information beyond the classifier.")
    w(f"* Within fraud rows the deviation correlates with the classifier score (Spearman {sim['within_fraud_spearman_deviation_vs_classifier']:.2f}); within legitimate rows {sim['within_legit_spearman_deviation_vs_classifier']:.2f}.")
    s1 = sim["s1_minus_s0"]
    w(f"* S1 minus S0: ROC-AUC {s1['roc_auc']['difference']:+.4f} {ci(s1['roc_auc']['ci95'], 4)}, PR-AUC {s1['pr_auc']['difference']:+.4f} {ci(s1['pr_auc']['ci95'], 4)}.")
    zv = sim["near_constant_features"]
    w(f"* Near-constant features: {zv['p10_all']['share_with_a_zero_std_feature']*100:.1f} % of scored rows have at least one of the nine features with zero standard deviation in the customer's history "
      f"(legitimate {zv['p10_legit']['share_with_a_zero_std_feature']*100:.1f} %, fraud {zv['p10_fraud']['share_with_a_zero_std_feature']*100:.1f} %); the formula replaces that standard deviation by 1.\n")
    w("By fraud type (fraud of that type against all legitimate rows):\n")
    w("| Fraud type | Fraud rows | ROC-AUC (95 % CI) |")
    w("|---|---|---|")
    for k, v in d.items():
        if k.startswith("s0_type_"):
            w(f"| {k[8:]} | {v['fraud']} | {v['roc_auc']:.3f} {ci(v['roc_auc_ci95'])} |")
    w("\nBy history length (rows with the bin's number of earlier transactions):\n")
    w("| Earlier transactions | Fraud rows | ROC-AUC (95 % CI) |")
    w("|---|---|---|")
    for k, v in d.items():
        if k.startswith("s0_bin_"):
            w(f"| {k[7:]} | {v['fraud']} | {v['roc_auc']:.3f} {ci(v['roc_auc_ci95'])} |")
    w("\nNo fraud row in this generator has fewer than 10 earlier transactions, so the score's behaviour for fraud on short histories is **not testable here**.\n")
    w("**Circularity:** " + sim["circularity_note"] + "\n")

    w("## EXP3-CAL — is the Fraud Score a calibrated probability?\n")
    t = cal["pooled_test_all_rows"]
    w("Pooled test, all rows. Calibrators fitted on validation seeds only.\n")
    w("| Version | Brier | Log loss | ECE (equal width) | ECE (equal mass) | Calibration slope | Intercept |")
    w("|---|---|---|---|---|---|---|")
    for k in ("uncalibrated", "sigmoid", "isotonic", "prevalence_only"):
        v = t[k]
        w(f"| {k} | {v['brier']:.6f} | {v['log_loss']:.5f} | {v['ece_equal_width']:.5f} | {v['ece_equal_mass']:.5f} | " +
          (f"{v['calibration_slope']:.2f} | {v['calibration_intercept']:.2f} |" if 'calibration_slope' in v else "– | – |"))
    w("\nPaired differences versus the uncalibrated score (negative = better):\n")
    w("| Calibrator | Brier difference (95 % CI) | Log-loss difference (95 % CI) | Lower in every test seed | Protocol rule: useful |")
    w("|---|---|---|---|---|")
    for k, v in cal["paired_differences_vs_uncalibrated"].items():
        w(f"| {k} | {v['brier']['difference']:+.6f} {ci(v['brier']['ci95'], 6)} | {v['log_loss']['difference']:+.5f} {ci(v['log_loss']['ci95'], 5)} | {v['lower_in_every_test_seed']} | {v['protocol_rule_calibrator_useful']} |")
    r = cal["ranking_metrics_pooled_test"]
    w(f"\nRanking: ROC-AUC {r['uncalibrated']['roc_auc']:.4f} (uncalibrated and sigmoid), {r['isotonic']['roc_auc']:.4f} (isotonic, {r['isotonic']['distinct_score_values']} distinct values); PR-AUC {r['uncalibrated']['pr_auc']:.4f} and {r['isotonic']['pr_auc']:.4f}.\n")
    w("Reliability (uncalibrated, 15 equal-mass bins; the first 14 bins hold only low scores):\n")
    w("| Bin | Rows | Mean predicted | Observed fraud rate | Fraud rows |")
    w("|---|---|---|---|---|")
    for i, b in enumerate(cal["reliability_uncalibrated_equal_mass_15"], 1):
        w(f"| {i} | {b['n']:,} | {b['mean_predicted']:.5f} | {b['observed_rate']:.5f} | {b['fraud']} |")
    w("\n" + cal["note"] + "\n")

    w("## EXP3-ABL — baselines and ablations on identical rows (pooled test)\n")
    w("Cut-off per model: the lowest score whose false-positive rate on validation seeds is ≤ 1 %, then frozen. Rows with ≥ 10 earlier transactions.\n")
    w("| Model | PR-AUC (95 % CI) | ROC-AUC | Recall (95 % CI) | Precision | F1 | Legit. alerts per 1,000 legit. | First-fraud recall | TP | FP | FN | TN |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for k, v in abl["pooled_test"]["p10"].items():
        c = v["confusion"]
        w(f"| {v['label']} | {v['pr_auc']:.3f} {ci(v['pr_auc_ci95'])} | {v['roc_auc']:.3f} | {v['recall']:.3f} {ci(v['recall_ci95'])} | {v['precision']:.3f} | {v['f1']:.3f} | "
          f"{v['legit_alerts_per_1000_legit']:.2f} | {v['first_fraud_recall']:.3f} | {c['tp']} | {c['fp']} | {c['fn']} | {c['tn']} |")
    w("\nPaired differences (rows with ≥ 10 earlier transactions):\n")
    w("| Comparison | PR-AUC diff. (95 % CI) | ROC-AUC diff. | Recall diff. (95 % CI) | Legit. alerts / 1,000 diff. (95 % CI) |")
    w("|---|---|---|---|---|")
    for k, v in abl["paired"]["p10"].items():
        rec = v.get("recall")
        la = v.get("legit_alerts_per_1000_legit")
        w(f"| {k.replace('_minus_', ' − ')} | {v['pr_auc']['difference']:+.3f} {ci(v['pr_auc']['ci95'])} | {v['roc_auc']['difference']:+.3f} {ci(v['roc_auc']['ci95'])} | "
          + (f"{rec['difference']:+.3f} {ci(rec['ci95'])}" if rec else "–") + " | " + (f"{la['difference']:+.2f} {ci(la['ci95'], 2)}" if la else "–") + " |")
    w("\nAll rows (including those with fewer than 10 earlier transactions; none of them is fraud). Cold-start rows are scored by each model's own rule: the default and DNN sets impute neutral values, "
      "the re-trained baselines have no cold-start rule, so their extra false alerts on short histories reflect that, not only the missing LSTM.\n")
    w("| Model | PR-AUC | ROC-AUC | Legit. alerts per 1,000 legit. |")
    w("|---|---|---|---|")
    for k, v in abl["pooled_test"]["all"].items():
        w(f"| {v['label']} | {v['pr_auc']:.3f} | {v['roc_auc']:.3f} | {v['legit_alerts_per_1000_legit']:.2f} |")
    cold_rows = pop["test"]["rows"] - pop["test"]["p10_rows"]
    w(f"\nFalse alerts on the {cold_rows:,} test rows that have fewer than 10 earlier transactions (all legitimate), at the same frozen cut-offs "
      "(all-rows false positives minus rows-with-history false positives):\n")
    w("| Model | False alerts | Share of those rows |")
    w("|---|---|---|")
    for k, v in abl["pooled_test"]["all"].items():
        fp = v["confusion"]["fp"] - abl["pooled_test"]["p10"][k]["confusion"]["fp"]
        w(f"| {v['label']} | {fp:,} | {100 * fp / cold_rows:.1f} % |")
    w("\nThis is the new-customer weakness the project already documents (cold-start rows get neutral inputs and score high); this experiment measures it on fresh synthetic data but does not test any remedy.\n")
    w("\n## Reproducibility\n")
    w(f"* Bootstrap: {meta['bootstrap']['reps']} replicates, seed {meta['bootstrap']['seed']}, unit: {meta['bootstrap']['unit']}.")
    w("* Software: " + ", ".join(f"{k} {v}" for k, v in meta["versions"].items()) + ".")
    w(f"* Re-trained baselines: random forest and logistic regression fitted on {meta['baselines']['training_rows']:,} training rows ({meta['baselines']['training_fraud']} fraud) of the seed-42 v2 dataset (SHA-256 `{meta['baselines']['dataset_sha256']}`).")
    w("* Per-row scores (about 54 MB) are not committed; their SHA-256 over the decompressed CSV content are in each results file (`meta.scores_content_sha256`) and `scripts` regenerate them deterministically (verified by a second full run).")
    (HERE / "RESULTS.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
